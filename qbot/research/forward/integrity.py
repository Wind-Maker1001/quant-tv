"""Integrity primitives for append-only FactorLab forward evidence.

The helpers in this module deliberately avoid resolving paths through links.
Forward evidence must stay below the caller-selected local repository and data
roots; accepting a symlink or Windows reparse point would make that boundary
ambiguous.  The source digest binds an activation to the executable research
implementation without including generated bytecode or mutable run outputs.
"""

from __future__ import annotations

from contextlib import contextmanager
import hashlib
import os
from pathlib import Path
import stat
import time
from typing import Iterator, List, Tuple

from qbot.research.errors import FactorLabError


class ForwardIntegrityError(FactorLabError):
    """Raised when a forward-evidence path or source tree is unsafe."""


class ForwardWorkflowLockError(ForwardIntegrityError):
    """Raised when an exclusive forward workflow lock cannot be acquired."""


def _absolute_without_resolving(path: Path) -> Path:
    """Return a normalized absolute path without following filesystem links."""

    return Path(os.path.abspath(os.fspath(path)))


def _is_link_or_reparse(path: Path) -> bool:
    """Identify POSIX links and Windows junction/reparse-point components."""

    try:
        metadata = os.lstat(str(path))
    except OSError as exc:
        raise ForwardIntegrityError(
            "cannot inspect forward path component: %s" % path
        ) from exc
    if stat.S_ISLNK(metadata.st_mode):
        return True
    reparse_flag = getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x0400)
    attributes = getattr(metadata, "st_file_attributes", 0)
    return bool(attributes & reparse_flag)


def assert_no_link_components(path: Path) -> Path:
    """Reject links/reparse points in every existing path component.

    Missing trailing components are allowed so callers can validate a future
    output location before creating it.  Unlike :meth:`Path.resolve`, this
    routine never follows a link before deciding whether the path is safe.
    """

    candidate = _absolute_without_resolving(Path(path))
    components = []
    cursor = candidate
    while True:
        components.append(cursor)
        if cursor.parent == cursor:
            break
        cursor = cursor.parent
    for component in reversed(components):
        if os.path.lexists(str(component)) and _is_link_or_reparse(component):
            raise ForwardIntegrityError(
                "forward path contains a symlink or reparse point: %s" % component
            )
    return candidate


def _read_regular_file(path: Path) -> bytes:
    checked = assert_no_link_components(path)
    try:
        before = os.lstat(str(checked))
    except OSError as exc:
        raise ForwardIntegrityError("required source file is unavailable: %s" % path) from exc
    if not stat.S_ISREG(before.st_mode):
        raise ForwardIntegrityError("source entry is not a regular file: %s" % path)
    try:
        content = checked.read_bytes()
        after = os.lstat(str(checked))
    except OSError as exc:
        raise ForwardIntegrityError("cannot read source file: %s" % path) from exc
    identity_before = (
        before.st_dev,
        before.st_ino,
        before.st_size,
        getattr(before, "st_mtime_ns", None),
    )
    identity_after = (
        after.st_dev,
        after.st_ino,
        after.st_size,
        getattr(after, "st_mtime_ns", None),
    )
    if identity_before != identity_after or _is_link_or_reparse(checked):
        raise ForwardIntegrityError("source file changed while hashing: %s" % path)
    return content


def _source_entries(repo_root: Path) -> List[Tuple[str, Path]]:
    root = assert_no_link_components(repo_root)
    if not root.is_dir():
        raise ForwardIntegrityError("repository root is not a directory: %s" % root)
    source_root = root / "qbot" / "research"
    requirements = root / "dev" / "requirements-research.txt"
    assert_no_link_components(source_root)
    if not source_root.is_dir():
        raise ForwardIntegrityError(
            "research source directory is unavailable: %s" % source_root
        )

    python_files = []
    for current_text, directories, filenames in os.walk(
        str(source_root), topdown=True, followlinks=False
    ):
        current = Path(current_text)
        assert_no_link_components(current)
        for name in list(directories):
            assert_no_link_components(current / name)
        directories[:] = sorted(
            name for name in directories if name != "__pycache__"
        )
        for name in filenames:
            entry = current / name
            assert_no_link_components(entry)
            if name.endswith(".py"):
                python_files.append(entry)
    if not python_files:
        raise ForwardIntegrityError("research source tree contains no Python files")

    entries = python_files + [requirements]
    result = []
    for entry in entries:
        relative = entry.relative_to(root).as_posix()
        result.append((relative, entry))
    return sorted(result, key=lambda item: item[0])


def research_source_sha256(repo_root: Path) -> str:
    """Hash FactorLab runtime Python files and its pinned requirements file.

    Paths, lengths, and contents are framed explicitly, so two different file
    layouts cannot produce the same byte stream merely by concatenation.
    """

    digest = hashlib.sha256()
    digest.update(b"qbot-factorlab-source-v1\0")
    for relative, path in _source_entries(Path(repo_root)):
        relative_bytes = relative.encode("utf-8")
        content = _read_regular_file(path)
        digest.update(len(relative_bytes).to_bytes(8, "big"))
        digest.update(relative_bytes)
        digest.update(len(content).to_bytes(8, "big"))
        digest.update(content)
    return digest.hexdigest()


@contextmanager
def workflow_lock(
    lock_path: Path,
    *,
    timeout_seconds: float = 0.0,
    poll_interval_seconds: float = 0.1,
) -> Iterator[Path]:
    """Acquire a process-level O_EXCL lock without stale-lock deletion.

    The caller owns recovery from an abandoned lock.  Automatically deleting
    an old-looking lock could permit two data refreshes to overlap, which is a
    worse failure mode for formal forward evidence.
    """

    if timeout_seconds < 0:
        raise ForwardWorkflowLockError("timeout_seconds must be non-negative")
    if poll_interval_seconds <= 0:
        raise ForwardWorkflowLockError("poll_interval_seconds must be positive")
    candidate = assert_no_link_components(lock_path)
    candidate.parent.mkdir(parents=True, exist_ok=True)
    assert_no_link_components(candidate.parent)
    deadline = time.monotonic() + timeout_seconds
    descriptor = None
    token = os.urandom(16).hex()
    while descriptor is None:
        try:
            descriptor = os.open(
                str(candidate), os.O_CREAT | os.O_EXCL | os.O_WRONLY
            )
        except FileExistsError as exc:
            if time.monotonic() >= deadline:
                raise ForwardWorkflowLockError(
                    "forward workflow lock is already held: %s" % candidate
                ) from exc
            time.sleep(min(poll_interval_seconds, max(deadline - time.monotonic(), 0.0)))
    try:
        with os.fdopen(descriptor, "w", encoding="ascii", newline="\n") as handle:
            handle.write("pid=%d\ntoken=%s\n" % (os.getpid(), token))
            handle.flush()
            os.fsync(handle.fileno())
        yield candidate
    finally:
        try:
            content = candidate.read_text(encoding="ascii")
        except (OSError, UnicodeError) as exc:
            raise ForwardWorkflowLockError(
                "forward workflow lock disappeared or became unreadable: %s"
                % candidate
            ) from exc
        if ("token=%s\n" % token) not in content.splitlines(keepends=True):
            raise ForwardWorkflowLockError(
                "forward workflow lock ownership changed: %s" % candidate
            )
        try:
            candidate.unlink()
        except OSError as exc:
            raise ForwardWorkflowLockError(
                "cannot release forward workflow lock: %s" % candidate
            ) from exc


