def test_ratio_bound_has_independent_exact_oracle_and_returns_no_factor():
    raw = dict(zip(pilot.FIELDS, map(Decimal, ("1", "2", "1", "2"))))
    adjusted = dict(zip(pilot.FIELDS, map(Decimal, ("10", "30", "10", "30"))))
    result = pilot.ratio_error_bound(raw, adjusted)
    assert isinstance(result, Decimal)
    assert abs(float(result) - float(Fraction(10, 3))) < 1e-15
    assert pilot.ratio_error_bound(raw, {f: raw[f] * 10 for f in pilot.FIELDS}) == 0


def test_affine_cash_identity_uses_event_date_without_fitting_anchor():
    raw, adjusted = {}, {}
    cash = Decimal("0.41")
    for day in pilot.DATES:
        raw[day] = {f: Decimal(i + 10) for i, f in enumerate(pilot.FIELDS)}
        adjusted[day] = {f: 2 * (p + (cash if day >= "2025-07-16" else 0)) + 3
                         for f, p in raw[day].items()}
    assert pilot.affine_error_bound(raw, adjusted, cash, "2025-07-16") == 0
    adjusted["2025-07-10"]["open"] += 1
    assert pilot.affine_error_bound(raw, adjusted, cash, "2025-07-16") >= Decimal("0.5")


